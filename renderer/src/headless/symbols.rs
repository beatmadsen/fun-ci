//! Marks the table draws that the `font8x8` fonts lack, drawn here in the
//! same eight rows of eight pixels, bit 0 leftmost.

const SYMBOLS: [(char, [u8; 8]); 8] = [
    ('✓', [0x00, 0xC0, 0x60, 0x30, 0x1B, 0x0E, 0x04, 0x00]),
    ('✗', [0x00, 0xC3, 0x66, 0x3C, 0x3C, 0x66, 0xC3, 0x00]),
    ('▲', [0x00, 0x08, 0x1C, 0x1C, 0x3E, 0x3E, 0x7F, 0x00]),
    ('◌', [0x00, 0x24, 0x00, 0x81, 0x00, 0x81, 0x00, 0x24]),
    ('↯', [0x10, 0x08, 0x04, 0x3E, 0x10, 0x48, 0x70, 0x78]),
    ('❯', [0x00, 0x06, 0x0C, 0x18, 0x0C, 0x06, 0x00, 0x00]),
    ('…', [0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x49, 0x00]),
    ('–', [0x00, 0x00, 0x00, 0x00, 0x7E, 0x00, 0x00, 0x00]),
];

/// The rows of `ch`, if it is one of the table's marks.
#[must_use]
pub fn symbol(ch: char) -> Option<[u8; 8]> {
    SYMBOLS.iter().find(|(c, _)| *c == ch).map(|(_, rows)| *rows)
}
